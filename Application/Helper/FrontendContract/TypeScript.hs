frontendSurfaceMountConfigName :: SurfaceIR -> Text
frontendSurfaceMountConfigName surface = surfaceTypePrefix surface <> "MountConfig"

renderScope :: SurfaceIR -> ScopeIR -> [Text]
renderScope surface scope =
    renderRecordGuarded (surfaceTypePrefix surface <> typeNameFromMarker scope.scopeMarker <> "Scope") scope.scopeFields

