renderFrontendContractTypeScript :: FrontendContractIR -> Either Text Text
renderFrontendContractTypeScript contract = do
    checked <- case checkedFrontendContractIR contract of
        Right value -> Right value
        Left diagnostics -> Left (Text.intercalate "\n" (fmap (.diagnosticMessage) diagnostics))
    pure (Text.unlines (header checked <> renderDerivedSurfaceWireTypes checked.contractSurfaces <> concatMap renderGlobal checked.contractGlobals <> concatMap renderSurface checked.contractSurfaces <> renderFrontendSurfaceRuntime checked.contractSurfaces))

data WirePrimitiveTypeScript = WirePrimitiveTypeScript
    { primitiveWire      :: !WireIR
    , primitiveTypeName  :: !Text
    , primitiveTsRuntime :: !Text
    }

wirePrimitiveTypes :: [WirePrimitiveTypeScript]
wirePrimitiveTypes =
    [ WirePrimitiveTypeScript WireUuidIR "FrontendContractUuid" "string"
    , WirePrimitiveTypeScript WireDayIR "FrontendContractDay" "string"
    ]

wirePrimitiveTypeName :: WireIR -> Text
wirePrimitiveTypeName wire =
    case List.find ((== wire) . (.primitiveWire)) wirePrimitiveTypes of
        Just primitive -> primitive.primitiveTypeName
        Nothing        -> error ("No TypeScript primitive alias registered for " <> show wire)

wirePrimitiveRuntimeType :: WireIR -> Text
wirePrimitiveRuntimeType wire =
    case List.find ((== wire) . (.primitiveWire)) wirePrimitiveTypes of
        Just primitive -> primitive.primitiveTsRuntime
        Nothing        -> error ("No TypeScript primitive runtime type registered for " <> show wire)

renderWirePrimitiveAliases :: FrontendContractIR -> [Text]
renderWirePrimitiveAliases contract =
    [ "export type " <> primitive.primitiveTypeName <> " = " <> primitive.primitiveTsRuntime <> ";"
    | primitive <- wirePrimitiveTypes
    , any (wireContains primitive.primitiveWire) (browserReachableWires contract)
    ]

browserReachableWires :: FrontendContractIR -> [WireIR]
browserReachableWires contract =
    concatMap globalWires contract.contractGlobals
        <> concatMap surfaceWires contract.contractSurfaces
  where
    globalWires global = concatMap primitiveWires global.globalPrimitives
    primitiveWires = \case
        GlobalSchemaIR BrowserUnreachableIR _ -> []
        GlobalSchemaIR _ schema -> fmap (.fieldWire) (schemaFields schema)
        GlobalEventIR BrowserUnreachableIR _ _ _ -> []
        GlobalEventIR BrowserTypeOnlyIR _ _ _ -> []
        GlobalEventIR _ _ _ fields -> fmap (.fieldWire) fields
        _ -> []
    surfaceWires surface =
        fmap (.fieldWire)
            ( concatMap (.scopeFields) surface.surfaceScopes
                <> concatMap (.fragmentParams) surface.surfaceFragments
                <> concatMap reachableDtoFields surface.surfaceDtos
            )
    reachableDtoFields dto =
        case dto.surfaceDtoReachability of
            BrowserUnreachableIR -> []
            _                    -> schemaFields dto.surfaceDtoSchema

wireContains :: WireIR -> WireIR -> Bool
wireContains expected wire
    | expected == wire = True
wireContains expected (WireListIR inner) = wireContains expected inner
wireContains expected (WireMapIR key value) = wireContains expected key || wireContains expected value
wireContains expected (WireOptionalIR inner) = wireContains expected inner
wireContains expected (WireNullableIR inner) = wireContains expected inner
wireContains _ _ = False

header :: FrontendContractIR -> [Text]
header contract =
    [ "// Generated by Application.Helper.FrontendContract. Do not edit." ]
        <> renderWirePrimitiveAliases contract
        <> [ ""
           , "function isRecord(value: unknown): value is Record<string, unknown> {"
           , "    return typeof value === \"object\" && value !== null && !Array.isArray(value);"
           , "}"
           , "function hasExactKeys(value: Record<string, unknown>, keys: readonly string[], requiredKeys: readonly string[] = keys): boolean {"
           , "    const valueKeys = Object.keys(value);"
           , "    return valueKeys.every((key) => keys.includes(key)) && requiredKeys.every((key) => Object.prototype.hasOwnProperty.call(value, key));"
           , "}"
           , ""
           ]

semanticSurfaceFieldName, semanticScopeFieldName, semanticKindFieldName, semanticParamsFieldName :: Text
semanticSurfaceFieldName = surfaceWireFieldName SurfaceWireSurfaceField
semanticScopeFieldName = surfaceWireFieldName SurfaceWireScopeField
semanticKindFieldName = surfaceWireFieldName SurfaceWireKindField
semanticParamsFieldName = surfaceWireFieldName SurfaceWireParamsField

renderDerivedSurfaceWireTypes :: [SurfaceIR] -> [Text]
renderDerivedSurfaceWireTypes surfaces =
    concatMap renderSurfaceScopeUnion surfaces
        <> concatMap renderSurfaceFragmentKeyUnion surfaces
        <> renderTopLevelSurfaceScopeUnion surfaces
        <> renderTopLevelSurfaceFragmentKeyUnion surfaces
        <> renderTopLevelInteractionSurfaceVocabulary surfaces

renderSurfaceScopeUnion :: SurfaceIR -> [Text]
renderSurfaceScopeUnion surface =
    [ "export type " <> surfaceScopeUnionName surface <> " =" ]
        <> renderNamedUnion scopeTypes
        <> renderGuard (surfaceScopeUnionName surface) (orExpression ["is" <> scopeType <> "(value)" | scopeType <- scopeTypes])
    where
        scopeTypes = [surfaceScopeTypeName surface scope.scopeMarker | scope <- surface.surfaceScopes]

renderSurfaceFragmentKeyUnion :: SurfaceIR -> [Text]
renderSurfaceFragmentKeyUnion surface =
    [ "export type " <> surfaceFragmentKeyUnionName surface <> " =" ]
        <> renderFragmentKeyCases surface fragments
        <> renderGuard (surfaceFragmentKeyUnionName surface) (orExpression (fmap (fragmentKeyGuard surface) fragments))
    where
        fragments = [(fragment.fragmentMarker, fragment.fragmentName, fragment.fragmentParams) | fragment <- surface.surfaceFragments]

renderTopLevelSurfaceScopeUnion :: [SurfaceIR] -> [Text]
renderTopLevelSurfaceScopeUnion surfaces =
    [ "export type SurfaceScope =" ]
        <> renderSurfaceScopeCases surfaces
        <> renderGuard "SurfaceScope" (orExpression (fmap surfaceScopeCaseGuard surfaces))

renderTopLevelSurfaceFragmentKeyUnion :: [SurfaceIR] -> [Text]
renderTopLevelSurfaceFragmentKeyUnion surfaces =
    [ "export type SurfaceFragmentKey =" ]
        <> renderTopLevelFragmentKeyCases surfaces
        <> renderGuard "SurfaceFragmentKey" (orExpression (fmap surfaceFragmentKeyCaseGuard surfaces))
        <> [ "function __canonicalFrontendContractJson(value: unknown): string {"
           , "    if (Array.isArray(value)) return `[${value.map(__canonicalFrontendContractJson).join(\",\")}]`;"
           , "    if (isRecord(value)) return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${__canonicalFrontendContractJson(value[key])}`).join(\",\")}}`;"
           , "    return JSON.stringify(value) ?? \"null\";"
           , "}"
           , "export function surfaceFragmentKeyIdentity(value: SurfaceFragmentKey): string {"
           , "    return __canonicalFrontendContractJson([value." <> semanticSurfaceFieldName <> ", value." <> semanticKindFieldName <> ", value." <> semanticParamsFieldName <> "]);"
           , "}"
           , "export function surfaceFragmentKeysEqual(left: SurfaceFragmentKey, right: SurfaceFragmentKey): boolean {"
           , "    return surfaceFragmentKeyIdentity(left) === surfaceFragmentKeyIdentity(right);"
           , "}"
           , ""
           ]

renderTopLevelInteractionSurfaceVocabulary :: [SurfaceIR] -> [Text]
renderTopLevelInteractionSurfaceVocabulary surfaces =
    renderTopLevelStringUnion "FrontendSurfaceInteractionSurfaceName" (fmap (.surfaceName) interactionSurfaces)
    where
        interactionSurfaces = filter surfaceHasBrowserInteraction surfaces

renderTopLevelStringUnion :: Text -> [Text] -> [Text]
renderTopLevelStringUnion typeName rawValues =
    [ "export type " <> typeName <> " = " <> renderStringUnion values <> ";"
    , "export function is" <> typeName <> "(value: unknown): value is " <> typeName <> " {"
    , "    return typeof value === \"string\" && [" <> Text.intercalate ", " (fmap quote values) <> "].includes(value);"
    , "}"
    , ""
    ]
    where
        values = List.nub rawValues

renderStringUnion :: [Text] -> Text
renderStringUnion values =
    case values of
        [] -> "never"
        _  -> Text.intercalate " | " (fmap quote values)

renderNamedUnion :: [Text] -> [Text]
renderNamedUnion names =
    case names of
        [] -> ["    never;", ""]
        _  -> zipWith render names [0 :: Int ..]
    where
        render name index = (if index == 0 then "    " else "  | ") <> name <> if index == length names - 1 then ";" else ""

renderSurfaceScopeCases :: [SurfaceIR] -> [Text]
renderSurfaceScopeCases surfaces =
    case surfaces of
        [] -> ["    never;", ""]
        _  -> zipWith render surfaces [0 :: Int ..]
    where
        render surface index =
            (if index == 0 then "    " else "  | ") <> "{ " <> semanticSurfaceFieldName <> ": " <> quote surface.surfaceName <> "; " <> semanticScopeFieldName <> ": " <> surfaceScopeUnionName surface <> " }" <> if index == length surfaces - 1 then ";" else ""

renderFragmentKeyCases :: SurfaceIR -> [(Text, Text, [FieldIR])] -> [Text]
renderFragmentKeyCases _ [] = ["    never;", ""]
renderFragmentKeyCases surface fragments = zipWith render fragments [0 :: Int ..]
    where
        render (marker, fragmentName, fields) index =
            (if index == 0 then "    " else "  | ") <> "{ " <> semanticKindFieldName <> ": " <> quote fragmentName <> "; " <> semanticParamsFieldName <> ": " <> fragmentParamsType surface marker fields <> " }" <> if index == length fragments - 1 then ";" else ""

renderTopLevelFragmentKeyCases :: [SurfaceIR] -> [Text]
renderTopLevelFragmentKeyCases [] = ["    never;", ""]
renderTopLevelFragmentKeyCases surfaces = zipWith render surfaces [0 :: Int ..]
    where
        render surface index =
            (if index == 0 then "    " else "  | ") <> "({ " <> semanticSurfaceFieldName <> ": " <> quote surface.surfaceName <> " } & " <> surfaceFragmentKeyUnionName surface <> ")" <> if index == length surfaces - 1 then ";" else ""

surfaceScopeCaseGuard :: SurfaceIR -> Text
surfaceScopeCaseGuard surface =
    "(isRecord(value) && hasExactKeys(value, ["
        <> quote semanticSurfaceFieldName
        <> ", "
        <> quote semanticScopeFieldName
        <> "]) && value."
        <> semanticSurfaceFieldName
        <> " === "
        <> quote surface.surfaceName
        <> " && is"
        <> surfaceScopeUnionName surface
        <> "(value."
        <> semanticScopeFieldName
        <> "))"

surfaceFragmentKeyCaseGuard :: SurfaceIR -> Text
surfaceFragmentKeyCaseGuard surface =
    "(isRecord(value) && hasExactKeys(value, ["
        <> Text.intercalate ", " (fmap quote [semanticSurfaceFieldName, semanticKindFieldName, semanticParamsFieldName])
        <> "]) && value."
        <> semanticSurfaceFieldName
        <> " === "
        <> quote surface.surfaceName
        <> " && is"
        <> surfaceFragmentKeyUnionName surface
        <> "({ "
        <> semanticKindFieldName
        <> ": value."
        <> semanticKindFieldName
        <> ", "
        <> semanticParamsFieldName
        <> ": value."
        <> semanticParamsFieldName
        <> " }))"

fragmentKeyGuard :: SurfaceIR -> (Text, Text, [FieldIR]) -> Text
fragmentKeyGuard _surface (_marker, fragmentName, fields) =
    "(isRecord(value) && hasExactKeys(value, ["
        <> Text.intercalate ", " (fmap quote [semanticKindFieldName, semanticParamsFieldName])
        <> "]) && value."
        <> semanticKindFieldName
        <> " === "
        <> quote fragmentName
        <> " && ("
        <> paramsGuard
        <> "))"
    where
        paramsAccess = "value[" <> quote semanticParamsFieldName <> "]"
        paramsGuard
            | null fields = paramsAccess <> " === null || " <> recordGuardExpressionWithAccess paramsAccess fields
            | otherwise = recordGuardExpressionWithAccess paramsAccess fields

recordGuardExpressionWithAccess :: Text -> [FieldIR] -> Text
recordGuardExpressionWithAccess access fields = Text.replace "value" access (recordGuardExpression fields)

fragmentParamsType :: SurfaceIR -> Text -> [FieldIR] -> Text
fragmentParamsType surface marker fields
    | null fields = surfaceFragmentParamsTypeName surface marker <> " | null"
    | otherwise = surfaceFragmentParamsTypeName surface marker

orExpression :: [Text] -> Text
orExpression expressions =
    case expressions of
        [] -> "false"
        _  -> "(" <> Text.intercalate " || " expressions <> ")"

surfaceScopeUnionName :: SurfaceIR -> Text
surfaceScopeUnionName surface = surfaceTypePrefix surface <> "SurfaceScope"

surfaceFragmentKeyUnionName :: SurfaceIR -> Text
surfaceFragmentKeyUnionName surface = surfaceTypePrefix surface <> "SurfaceFragmentKey"

surfaceScopeTypeName :: SurfaceIR -> Text -> Text
surfaceScopeTypeName surface marker = surfaceTypePrefix surface <> typeNameFromMarker marker <> "Scope"

surfaceFragmentParamsTypeName :: SurfaceIR -> Text -> Text
surfaceFragmentParamsTypeName surface marker = surfaceTypePrefix surface <> typeNameFromMarker marker <> "FragmentParams"

renderGlobal :: GlobalIR -> [Text]
renderGlobal global =
    concatMap renderGlobalPrimitive global.globalPrimitives
        <> concatMap (renderGlobalProjection global.globalPrimitives) [projection | GlobalProjectionIR projection <- global.globalPrimitives]

renderGlobalPrimitive :: GlobalPrimitiveIR -> [Text]
renderGlobalPrimitive = \case
    GlobalSchemaIR BrowserUnreachableIR _ -> []
    GlobalSchemaIR reachability schema -> renderSchemaFor reachability schema
    GlobalEventIR BrowserUnreachableIR _ _ _ -> []
    GlobalEventIR reachability marker eventName fields ->
        renderEventDetail reachability (typeNameFromMarker marker <> "EventDetail") fields
            <> ["export const " <> constName marker <> "Event = " <> quote eventName <> " as const;", ""]
    GlobalDomIdIR marker domId -> ["export const " <> constName marker <> "DomId = " <> quote domId <> " as const;", ""]
    GlobalServerDomIdIR _ _ -> []
    GlobalDomAttrIR marker attr -> ["export const " <> constName marker <> "DomAttr = " <> quote attr <> " as const;", ""]
    GlobalServerDomAttrIR _ _ -> []
    GlobalDomValueIR marker value -> ["export const " <> constName marker <> "DomValue = " <> quote value <> " as const;", ""]
    GlobalFieldNameIR marker name -> ["export const " <> constName marker <> "FieldName = " <> quote name <> " as const;", ""]
    GlobalDomTokenIR marker token -> ["export const " <> constName marker <> "DomToken = " <> quote token <> " as const;", ""]
    GlobalConstantIR marker value -> ["export const " <> constName marker <> " = " <> quote value <> " as const;", ""]
    GlobalProjectionIR _ -> []
    GlobalAppShellActionIR _ -> []

renderGlobalProjection :: [GlobalPrimitiveIR] -> GlobalProjectionIR -> [Text]
renderGlobalProjection primitives = \case
    InteractionDomProjectionIR -> renderInteractionDomGroup primitives

renderInteractionDomGroup :: [GlobalPrimitiveIR] -> [Text]
renderInteractionDomGroup primitives =
    [ "export type InteractionDomAttributes = {"
    ]
        <> fmap renderAttrType attrs
        <> [ "};"
           , "export type InteractionDomValues = {"
           ]
        <> fmap renderValueType values
        <> [ "};"
           , "export type InteractionPointerFields = {"
           ]
        <> fmap renderFieldType fields
        <> [ "};"
           , "export type InteractionDom = { attributes: InteractionDomAttributes; values: InteractionDomValues; pointerFields: InteractionPointerFields };"
           , "export const InteractionDom: InteractionDom = {"
           , "    attributes: { " <> Text.intercalate ", " (fmap renderAttrValue attrs) <> " },"
           , "    values: { " <> Text.intercalate ", " (fmap renderDomValue values) <> " },"
           , "    pointerFields: { " <> Text.intercalate ", " (fmap renderFieldValue fields) <> " },"
           , "};"
           , ""
           ]
    where
        attrs = [(marker, value) | GlobalDomAttrIR marker value <- primitives]
        values = [(marker, value) | GlobalDomValueIR marker value <- primitives]
        fields = [(marker, value) | GlobalFieldNameIR marker value <- primitives]
        renderAttrType (marker, _) = "    " <> constName marker <> ": typeof " <> constName marker <> "DomAttr;"
        renderValueType (marker, _) = "    " <> constName marker <> ": typeof " <> constName marker <> "DomValue;"
        renderFieldType (marker, _) = "    " <> constName marker <> ": typeof " <> constName marker <> "FieldName;"
        renderAttrValue (marker, _) = constName marker <> ": " <> constName marker <> "DomAttr"
        renderDomValue (marker, _) = constName marker <> ": " <> constName marker <> "DomValue"
        renderFieldValue (marker, _) = constName marker <> ": " <> constName marker <> "FieldName"

renderSurface :: SurfaceIR -> [Text]
renderSurface surface =
    concatMap renderSurfaceDto surface.surfaceDtos
        <> concatMap (renderScope surface) surface.surfaceScopes
        <> concatMap (renderFragment surface) surface.surfaceFragments

renderSurfaceDto :: SurfaceDtoIR -> [Text]
renderSurfaceDto dto =
    case dto.surfaceDtoReachability of
        BrowserUnreachableIR -> []
        reachability -> renderSchemaFor reachability dto.surfaceDtoSchema

renderFrontendSurfaceRuntime :: [SurfaceIR] -> [Text]
renderFrontendSurfaceRuntime surfaces =
    renderFrontendSurfaceBrandAliases surfaces
        <> concatMap renderFrontendSurfaceDomTokenConstants surfaces
        <> concatMap renderFrontendSurfaceBrowserAttributeConstants surfaces
        <> concatMap renderFrontendSurfaceBrowserClosedStateTypes surfaces
        <> concatMap renderFrontendSurfaceCompleteSetSortKeyTypes surfaces
        <> concatMap renderFrontendSurfaceTabSetKeyTypes surfaces
        <> renderFrontendSurfaceRegistries surfaces
        <> renderFrontendSurfaceMountConfigTypes surfaces

renderFrontendSurfaceBrandAliases :: [SurfaceIR] -> [Text]
renderFrontendSurfaceBrandAliases surfaces =
    [ "export type " <> alias <> " = " <> wirePrimitiveTypeName WireUuidIR <> ";"
    | alias <- List.nub (concatMap surfaceUuidAliases surfaces)
    ] <> ["" | not (null (concatMap surfaceUuidAliases surfaces))]

surfaceUuidAliases :: SurfaceIR -> [Text]
surfaceUuidAliases surface =
    [ typeNameFromMarker field.fieldMarker
    | field <- surfaceFields surface
    , isUuidWire field.fieldWire
    ]

surfaceFields :: SurfaceIR -> [FieldIR]
surfaceFields surface =
    concatMap (.scopeFields) surface.surfaceScopes
        <> concatMap (.fragmentParams) surface.surfaceFragments
        <> concatMap (.htmxActionFields) surface.surfaceHtmxActions
        <> concatMap (.intentFields) surface.surfaceIntents
        <> concatMap snd surface.surfaceClientEvents
        <> concatMap reachableDtoFields surface.surfaceDtos
  where
    reachableDtoFields dto =
        case dto.surfaceDtoReachability of
            BrowserUnreachableIR -> []
            _                    -> schemaFields dto.surfaceDtoSchema

isUuidWire :: WireIR -> Bool
isUuidWire = \case
    WireUuidIR -> True
    WireOptionalIR inner -> isUuidWire inner
    WireNullableIR inner -> isUuidWire inner
    WireListIR inner -> isUuidWire inner
    _ -> False

renderFrontendSurfaceDomTokenConstants :: SurfaceIR -> [Text]
renderFrontendSurfaceDomTokenConstants surface =
    [ "export const " <> constName token <> "DomToken = " <> quote token <> " as const;"
    | token <- surface.surfaceBrowserDomTokens
    ] <> ["" | not (null surface.surfaceBrowserDomTokens)]

renderFrontendSurfaceBrowserAttributeConstants :: SurfaceIR -> [Text]
renderFrontendSurfaceBrowserAttributeConstants surface =
    [ "export const " <> surfaceBrowserAttributeConstName surface attribute <> " = " <> quote attribute.browserAttributeDomAttribute <> " as const;"
    | attribute <- surface.surfaceBrowserRoles <> surface.surfaceBrowserStates
    ] <> ["" | not (null surface.surfaceBrowserRoles && null surface.surfaceBrowserStates)]

renderFrontendSurfaceBrowserClosedStateTypes :: SurfaceIR -> [Text]
renderFrontendSurfaceBrowserClosedStateTypes surface =
    concatMap renderState surface.surfaceBrowserClosedStates
  where
    renderState state =
        let stateType = surfaceBrowserClosedStateTypeName surface state
         in [ "export const " <> surfaceBrowserClosedStateValuesConstName surface state <> " = "
                <> objectLiteral [(value, quote value) | value <- state.browserClosedStateValues]
                <> " as const;"
            , "export type " <> stateType <> " = " <> renderStringUnion state.browserClosedStateValues <> ";"
            , "export function is" <> stateType <> "(value: unknown): value is " <> stateType <> " {"
            , "    return typeof value === \"string\" && " <> arrayLiteral (map quote state.browserClosedStateValues) <> ".includes(value);"
            , "}"
            , ""
            ]

surfaceBrowserClosedStateTypeName :: SurfaceIR -> BrowserClosedStateIR -> Text
surfaceBrowserClosedStateTypeName surface state =
    typeNameFromMarker (surface.surfaceName <> "-" <> state.browserClosedStateAttribute.browserAttributeName <> "-state")

surfaceBrowserClosedStateValuesConstName :: SurfaceIR -> BrowserClosedStateIR -> Text
surfaceBrowserClosedStateValuesConstName surface state =
    constName (surface.surfaceName <> "-" <> state.browserClosedStateAttribute.browserAttributeName <> "-states")

surfaceBrowserAttributeConstName :: SurfaceIR -> BrowserAttributeIR -> Text
surfaceBrowserAttributeConstName surface attribute =
    constName (surface.surfaceName <> "-" <> attribute.browserAttributeName) <> "DomAttr"

renderFrontendSurfaceRegistries :: [SurfaceIR] -> [Text]
renderFrontendSurfaceRegistries surfaces =
    ["export type FrontendSurfaceName = " <> renderStringUnion (fmap (.surfaceName) surfaces) <> ";"]
        <> renderFrontendSurfaceLinkedHighlightContracts surfaces
        <> renderFrontendSurfaceCompleteSetSortContracts surfaces
        <> renderFrontendSurfaceTabSetContracts surfaces
        <> renderFrontendSurfaceSidePanelContracts surfaces
        <> [ "export const FrontendSurfaceFragmentRegistry = " <> objectLiteral fragmentEntries <> " as const;"
           , "export function isFrontendSurfaceName(value: unknown): value is FrontendSurfaceName {"
           , "    return typeof value === \"string\" && Object.prototype.hasOwnProperty.call(FrontendSurfaceFragmentRegistry, value);"
           , "}"
           , "export function isFrontendSurfaceLiveFragmentName(surface: FrontendSurfaceName, value: unknown): value is string {"
           , "    return typeof value === \"string\" && (FrontendSurfaceFragmentRegistry[surface] as readonly string[]).includes(value);"
           , "}"
           , "export const FrontendSurfaceInteractionRegistry = " <> objectLiteral interactionEntries <> " as const;"
           , ""
           ]
  where
    fragmentEntries =
        [ (surface.surfaceName, arrayLiteral (fmap quote (surfaceLiveFragmentNames surface)))
        | surface <- surfaces
        ]
    interactionEntries =
        [ (surface.surfaceName, renderFrontendSurfaceInteractionDefinition surface)
        | surface <- surfaces
        , surfaceHasBrowserInteraction surface
        ]

renderFrontendSurfaceTabSetKeyTypes :: SurfaceIR -> [Text]
renderFrontendSurfaceTabSetKeyTypes surface =
    concatMap renderKeyType surface.surfaceTabSets
  where
    renderKeyType tabSet = renderTopLevelStringUnion (tabSetKeyTypeName tabSet) tabSet.tabSetKeys

tabSetKeyTypeName :: TabSetIR -> Text
tabSetKeyTypeName tabSet = typeNameFromMarker tabSet.tabSetMarker <> "Key"

renderFrontendSurfaceTabSetContracts :: [SurfaceIR] -> [Text]
renderFrontendSurfaceTabSetContracts surfaces =
    [ "export type FrontendSurfaceTabSetDefinition = { name: string; tabRoleAttribute: string; keys: ReadonlyArray<string>; defaultKey: string; isKey: (value: unknown) => boolean };"
    , "export const FrontendSurfaceTabSetRegistry: Record<FrontendSurfaceName, ReadonlyArray<FrontendSurfaceTabSetDefinition>> = " <> objectLiteral entries <> ";"
    , ""
    ]
  where
    entries =
        [ (surface.surfaceName, arrayLiteral (map (renderTabSet surface) surface.surfaceTabSets))
        | surface <- surfaces
        ]

renderTabSet :: SurfaceIR -> TabSetIR -> Text
renderTabSet surface tabSet = objectLiteral
    [ ("name", quote tabSet.tabSetName)
    , ("tabRoleAttribute", surfaceBrowserAttributeConstName surface tabSet.tabSetRole)
    , ("keys", arrayLiteral (map quote tabSet.tabSetKeys))
    , ("defaultKey", quote tabSet.tabSetDefaultKey)
    , ("isKey", "is" <> tabSetKeyTypeName tabSet)
    ]

renderFrontendSurfaceSidePanelContracts :: [SurfaceIR] -> [Text]
