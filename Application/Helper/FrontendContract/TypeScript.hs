module Application.Helper.FrontendContract.TypeScript
    ( renderFrontendContractTypeScript
    ) where

import Application.Helper.FrontendContract.IR
import qualified Data.Char as Char
import qualified Data.List as List
import qualified Data.Text as Text
import IHP.Prelude

renderFrontendContractTypeScript :: FrontendContractIR -> Either Text Text
renderFrontendContractTypeScript contract = do
    checked <- case checkedFrontendContractIR contract of
        Right value -> Right value
        Left diagnostics -> Left (Text.intercalate "\n" (fmap (.diagnosticMessage) diagnostics))
    pure (Text.unlines (header checked <> renderDerivedSurfaceWireTypes checked.contractSurfaces <> concatMap (renderGlobal checked.contractSurfaces) checked.contractGlobals <> concatMap renderSurface checked.contractSurfaces <> renderFrontendSurfaceRuntime checked.contractSurfaces))

data WirePrimitiveTypeScript = WirePrimitiveTypeScript
    { primitiveWire      :: !WireIR
    , primitiveTypeName  :: !Text
    , primitiveTsRuntime :: !Text
    }

wirePrimitiveTypes :: [WirePrimitiveTypeScript]
wirePrimitiveTypes =
    [ WirePrimitiveTypeScript WireUuidIR "FrontendContractUuid" "string"
    , WirePrimitiveTypeScript WireDayIR "FrontendContractDay" "string"
    ]

wirePrimitiveTypeName :: WireIR -> Text
wirePrimitiveTypeName wire =
    case List.find ((== wire) . (.primitiveWire)) wirePrimitiveTypes of
        Just primitive -> primitive.primitiveTypeName
        Nothing        -> error ("No TypeScript primitive alias registered for " <> show wire)

wirePrimitiveRuntimeType :: WireIR -> Text
wirePrimitiveRuntimeType wire =
    case List.find ((== wire) . (.primitiveWire)) wirePrimitiveTypes of
        Just primitive -> primitive.primitiveTsRuntime
        Nothing        -> error ("No TypeScript primitive runtime type registered for " <> show wire)

renderWirePrimitiveAliases :: FrontendContractIR -> [Text]
renderWirePrimitiveAliases contract =
    [ "export type " <> primitive.primitiveTypeName <> " = " <> primitive.primitiveTsRuntime <> ";"
    | primitive <- wirePrimitiveTypes
    , any (wireContains primitive.primitiveWire) (browserReachableWires contract)
    ]

browserReachableWires :: FrontendContractIR -> [WireIR]
browserReachableWires contract =
    concatMap globalWires contract.contractGlobals
        <> concatMap surfaceWires contract.contractSurfaces
  where
    globalWires global = concatMap primitiveWires global.globalPrimitives
    primitiveWires = \case
        GlobalSchemaIR BrowserUnreachableIR _ -> []
        GlobalSchemaIR _ schema -> fmap (.fieldWire) (schemaFields schema)
        GlobalEventIR BrowserUnreachableIR _ _ _ -> []
        GlobalEventIR BrowserTypeOnlyIR _ _ _ -> []
        GlobalEventIR _ _ _ fields -> fmap (.fieldWire) fields
        _ -> []
    surfaceWires surface =
        fmap (.fieldWire)
            (concatMap (.scopeFields) surface.surfaceScopes <> concatMap (.fragmentParams) surface.surfaceFragments)

wireContains :: WireIR -> WireIR -> Bool
wireContains expected wire
    | expected == wire = True
wireContains expected (WireListIR inner) = wireContains expected inner
wireContains expected (WireMapIR key value) = wireContains expected key || wireContains expected value
wireContains expected (WireOptionalIR inner) = wireContains expected inner
wireContains expected (WireNullableIR inner) = wireContains expected inner
wireContains _ _ = False

header :: FrontendContractIR -> [Text]
header contract =
    [ "// Generated by Application.Helper.FrontendContract. Do not edit." ]
        <> renderWirePrimitiveAliases contract
        <> [ ""
           , "function isRecord(value: unknown): value is Record<string, unknown> {"
           , "    return typeof value === \"object\" && value !== null && !Array.isArray(value);"
           , "}"
           , "function hasExactKeys(value: Record<string, unknown>, keys: readonly string[]): boolean {"
           , "    return Object.keys(value).every((key) => keys.includes(key));"
           , "}"
           , ""
           ]

renderDerivedSurfaceWireTypes :: [SurfaceIR] -> [Text]
renderDerivedSurfaceWireTypes surfaces =
    concatMap renderSurfaceScopeUnion surfaces
        <> concatMap renderSurfaceFragmentKeyUnion surfaces
        <> renderTopLevelSurfaceScopeUnion surfaces
        <> renderTopLevelSurfaceFragmentKeyUnion surfaces
        <> renderTopLevelInteractionSurfaceVocabulary surfaces

renderSurfaceScopeUnion :: SurfaceIR -> [Text]
renderSurfaceScopeUnion surface =
    [ "export type " <> surfaceScopeUnionName surface <> " =" ]
        <> renderNamedUnion scopeTypes
        <> renderGuard (surfaceScopeUnionName surface) (orExpression ["is" <> scopeType <> "(value)" | scopeType <- scopeTypes])
    where
        scopeTypes = [surfaceScopeTypeName surface scope.scopeMarker | scope <- surface.surfaceScopes]

renderSurfaceFragmentKeyUnion :: SurfaceIR -> [Text]
renderSurfaceFragmentKeyUnion surface =
    [ "export type " <> surfaceFragmentKeyUnionName surface <> " =" ]
        <> renderFragmentKeyCases surface fragments
        <> renderGuard (surfaceFragmentKeyUnionName surface) (orExpression (fmap (fragmentKeyGuard surface) fragments))
    where
        fragments = [(fragment.fragmentMarker, fragment.fragmentName, fragment.fragmentParams) | fragment <- surface.surfaceFragments]

renderTopLevelSurfaceScopeUnion :: [SurfaceIR] -> [Text]
renderTopLevelSurfaceScopeUnion surfaces =
    [ "export type SurfaceScope =" ]
        <> renderSurfaceScopeCases surfaces
        <> renderGuard "SurfaceScope" (orExpression (fmap surfaceScopeCaseGuard surfaces))

renderTopLevelSurfaceFragmentKeyUnion :: [SurfaceIR] -> [Text]
renderTopLevelSurfaceFragmentKeyUnion surfaces =
    [ "export type SurfaceFragmentKey =" ]
        <> renderTopLevelFragmentKeyCases surfaces
        <> renderGuard "SurfaceFragmentKey" (orExpression (fmap surfaceFragmentKeyCaseGuard surfaces))
        <> [ "function __canonicalFrontendContractJson(value: unknown): string {"
           , "    if (Array.isArray(value)) return `[${value.map(__canonicalFrontendContractJson).join(\",\")}]`;"
           , "    if (isRecord(value)) return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${__canonicalFrontendContractJson(value[key])}`).join(\",\")}}`;"
           , "    return JSON.stringify(value) ?? \"null\";"
           , "}"
           , "export function surfaceFragmentKeyIdentity(value: SurfaceFragmentKey): string {"
           , "    return __canonicalFrontendContractJson([value.surface, value.kind, value.params]);"
           , "}"
           , "export function surfaceFragmentKeysEqual(left: SurfaceFragmentKey, right: SurfaceFragmentKey): boolean {"
           , "    return surfaceFragmentKeyIdentity(left) === surfaceFragmentKeyIdentity(right);"
           , "}"
           , ""
           ]

renderTopLevelInteractionSurfaceVocabulary :: [SurfaceIR] -> [Text]
renderTopLevelInteractionSurfaceVocabulary surfaces =
    renderTopLevelStringUnion "FrontendSurfaceInteractionSurfaceName" (fmap (.surfaceName) interactionSurfaces)
    where
        interactionSurfaces = filter (\surface -> surface.surfaceName /= "surface-lab" && surfaceHasBrowserInteraction surface) surfaces

renderTopLevelStringUnion :: Text -> [Text] -> [Text]
renderTopLevelStringUnion typeName rawValues =
    [ "export type " <> typeName <> " = " <> renderStringUnion values <> ";"
    , "export function is" <> typeName <> "(value: unknown): value is " <> typeName <> " {"
    , "    return typeof value === \"string\" && [" <> Text.intercalate ", " (fmap quote values) <> "].includes(value);"
    , "}"
    , ""
    ]
    where
        values = List.nub rawValues

renderStringUnion :: [Text] -> Text
renderStringUnion values =
    case values of
        [] -> "never"
        _  -> Text.intercalate " | " (fmap quote values)

renderNamedUnion :: [Text] -> [Text]
renderNamedUnion names =
    case names of
        [] -> ["    never;", ""]
        _  -> zipWith render names [0 :: Int ..]
    where
        render name index = (if index == 0 then "    " else "  | ") <> name <> if index == length names - 1 then ";" else ""

renderSurfaceScopeCases :: [SurfaceIR] -> [Text]
renderSurfaceScopeCases surfaces =
    case surfaces of
        [] -> ["    never;", ""]
        _  -> zipWith render surfaces [0 :: Int ..]
    where
        render surface index =
            (if index == 0 then "    " else "  | ") <> "{ surface: " <> quote surface.surfaceName <> "; scope: " <> surfaceScopeUnionName surface <> " }" <> if index == length surfaces - 1 then ";" else ""

renderFragmentKeyCases :: SurfaceIR -> [(Text, Text, [FieldIR])] -> [Text]
renderFragmentKeyCases _ [] = ["    never;", ""]
renderFragmentKeyCases surface fragments = zipWith render fragments [0 :: Int ..]
    where
        render (marker, fragmentName, fields) index =
            (if index == 0 then "    " else "  | ") <> "{ kind: " <> quote fragmentName <> "; params: " <> fragmentParamsType surface marker fields <> " }" <> if index == length fragments - 1 then ";" else ""

renderTopLevelFragmentKeyCases :: [SurfaceIR] -> [Text]
renderTopLevelFragmentKeyCases [] = ["    never;", ""]
renderTopLevelFragmentKeyCases surfaces = zipWith render surfaces [0 :: Int ..]
    where
        render surface index =
            (if index == 0 then "    " else "  | ") <> "({ surface: " <> quote surface.surfaceName <> " } & " <> surfaceFragmentKeyUnionName surface <> ")" <> if index == length surfaces - 1 then ";" else ""

surfaceScopeCaseGuard :: SurfaceIR -> Text
surfaceScopeCaseGuard surface = "(isRecord(value) && hasExactKeys(value, [\"surface\", \"scope\"]) && value.surface === " <> quote surface.surfaceName <> " && is" <> surfaceScopeUnionName surface <> "(value.scope))"

surfaceFragmentKeyCaseGuard :: SurfaceIR -> Text
surfaceFragmentKeyCaseGuard surface =
    "(isRecord(value) && hasExactKeys(value, [\"surface\", \"kind\", \"params\"]) && value.surface === "
        <> quote surface.surfaceName
        <> " && is"
        <> surfaceFragmentKeyUnionName surface
        <> "({ kind: value.kind, params: value.params }))"

fragmentKeyGuard :: SurfaceIR -> (Text, Text, [FieldIR]) -> Text
fragmentKeyGuard surface (marker, fragmentName, fields) =
    "(isRecord(value) && hasExactKeys(value, [\"kind\", \"params\"]) && value.kind === " <> quote fragmentName <> " && (" <> paramsGuard <> "))"
    where
        paramsAccess = "value[\"params\"]"
        paramsGuard
            | null fields = paramsAccess <> " === null || " <> recordGuardExpressionWithAccess paramsAccess fields
            | otherwise = recordGuardExpressionWithAccess paramsAccess fields

recordGuardExpressionWithAccess :: Text -> [FieldIR] -> Text
recordGuardExpressionWithAccess access fields = Text.replace "value" access (recordGuardExpression fields)

fragmentParamsType :: SurfaceIR -> Text -> [FieldIR] -> Text
fragmentParamsType surface marker fields
    | null fields = surfaceFragmentParamsTypeName surface marker <> " | null"
    | otherwise = surfaceFragmentParamsTypeName surface marker

orExpression :: [Text] -> Text
orExpression expressions =
    case expressions of
        [] -> "false"
        _  -> "(" <> Text.intercalate " || " expressions <> ")"

surfaceScopeUnionName :: SurfaceIR -> Text
surfaceScopeUnionName surface = surfaceTypePrefix surface <> "SurfaceScope"

surfaceFragmentKeyUnionName :: SurfaceIR -> Text
surfaceFragmentKeyUnionName surface = surfaceTypePrefix surface <> "SurfaceFragmentKey"

surfaceScopeTypeName :: SurfaceIR -> Text -> Text
surfaceScopeTypeName surface marker = surfaceTypePrefix surface <> typeNameFromMarker marker <> "Scope"

surfaceFragmentParamsTypeName :: SurfaceIR -> Text -> Text
surfaceFragmentParamsTypeName surface marker = surfaceTypePrefix surface <> typeNameFromMarker marker <> "FragmentParams"

renderGlobal :: [SurfaceIR] -> GlobalIR -> [Text]
renderGlobal surfaces global = concatMap renderGlobalPrimitive global.globalPrimitives <> renderGlobalConvenienceGroups surfaces global

renderGlobalPrimitive :: GlobalPrimitiveIR -> [Text]
renderGlobalPrimitive = \case
    GlobalSchemaIR BrowserUnreachableIR _ -> []
    GlobalSchemaIR reachability schema -> renderSchemaFor reachability schema
    GlobalEventIR BrowserUnreachableIR _ _ _ -> []
    GlobalEventIR reachability marker eventName fields ->
        renderEventDetail reachability (typeNameFromMarker marker <> "EventDetail") fields
            <> ["export const " <> constName marker <> "Event = " <> quote eventName <> " as const;", ""]
    GlobalDomIdIR marker domId -> ["export const " <> constName marker <> "DomId = " <> quote domId <> " as const;", ""]
    GlobalServerDomIdIR _ _ -> []
    GlobalDomAttrIR marker attr -> ["export const " <> constName marker <> "DomAttr = " <> quote attr <> " as const;", ""]
    GlobalServerDomAttrIR _ _ -> []
    GlobalDomValueIR marker value -> ["export const " <> constName marker <> "DomValue = " <> quote value <> " as const;", ""]
    GlobalFieldNameIR marker name -> ["export const " <> constName marker <> "FieldName = " <> quote name <> " as const;", ""]
    GlobalDomTokenIR marker token -> ["export const " <> constName marker <> "DomToken = " <> quote token <> " as const;", ""]
    GlobalConstantIR marker value -> ["export const " <> constName marker <> " = " <> quote value <> " as const;", ""]
    GlobalAppShellActionIR _ -> []

renderGlobalConvenienceGroups :: [SurfaceIR] -> GlobalIR -> [Text]
renderGlobalConvenienceGroups _ global
    | global.globalName == "interaction" = renderInteractionDomGroup global.globalPrimitives
    | otherwise = []

renderInteractionDomGroup :: [GlobalPrimitiveIR] -> [Text]
renderInteractionDomGroup primitives =
    [ "export type InteractionDomAttributes = {"
    ]
        <> fmap renderAttrType attrs
        <> [ "};"
           , "export type InteractionDomValues = {"
           ]
        <> fmap renderValueType values
        <> [ "};"
           , "export type InteractionPointerFields = {"
           ]
        <> fmap renderFieldType fields
        <> [ "};"
           , "export type InteractionDom = { attributes: InteractionDomAttributes; values: InteractionDomValues; pointerFields: InteractionPointerFields };"
           , "export const InteractionDom: InteractionDom = {"
           , "    attributes: { " <> Text.intercalate ", " (fmap renderAttrValue attrs) <> " },"
           , "    values: { " <> Text.intercalate ", " (fmap renderDomValue values) <> " },"
           , "    pointerFields: { " <> Text.intercalate ", " (fmap renderFieldValue fields) <> " },"
           , "};"
           , ""
           ]
    where
        attrs = [(marker, value) | GlobalDomAttrIR marker value <- primitives]
        values = [(marker, value) | GlobalDomValueIR marker value <- primitives]
        fields = [(marker, value) | GlobalFieldNameIR marker value <- primitives]
        renderAttrType (marker, _) = "    " <> constName marker <> ": typeof " <> constName marker <> "DomAttr;"
        renderValueType (marker, _) = "    " <> constName marker <> ": typeof " <> constName marker <> "DomValue;"
        renderFieldType (marker, _) = "    " <> constName marker <> ": typeof " <> constName marker <> "FieldName;"
        renderAttrValue (marker, _) = constName marker <> ": " <> constName marker <> "DomAttr"
        renderDomValue (marker, _) = constName marker <> ": " <> constName marker <> "DomValue"
        renderFieldValue (marker, _) = constName marker <> ": " <> constName marker <> "FieldName"

renderSurface :: SurfaceIR -> [Text]
renderSurface surface =
    concatMap (renderScope surface) surface.surfaceScopes
        <> concatMap (renderFragment surface) surface.surfaceFragments

renderFrontendSurfaceRuntime :: [SurfaceIR] -> [Text]
renderFrontendSurfaceRuntime surfaces =
    renderFrontendSurfaceBrandAliases surfaces
        <> concatMap renderFrontendSurfaceDomTokenConstants surfaces
        <> renderFrontendSurfaceRegistries surfaces
        <> renderFrontendSurfaceMountConfigTypes surfaces

renderFrontendSurfaceBrandAliases :: [SurfaceIR] -> [Text]
renderFrontendSurfaceBrandAliases surfaces =
    [ "export type " <> alias <> " = " <> wirePrimitiveTypeName WireUuidIR <> ";"
    | alias <- List.nub (concatMap surfaceUuidAliases surfaces)
    ] <> ["" | not (null (concatMap surfaceUuidAliases surfaces))]

surfaceUuidAliases :: SurfaceIR -> [Text]
surfaceUuidAliases surface =
    [ typeNameFromMarker field.fieldMarker
    | field <- surfaceFields surface
    , isUuidWire field.fieldWire
    ]

surfaceFields :: SurfaceIR -> [FieldIR]
surfaceFields surface =
    concatMap (.scopeFields) surface.surfaceScopes
        <> concatMap (.fragmentParams) surface.surfaceFragments
        <> concatMap (.htmxActionFields) surface.surfaceHtmxActions
        <> concatMap (.intentFields) surface.surfaceIntents
        <> concatMap snd surface.surfaceClientEvents
        <> concatMap schemaFields surface.surfaceDtos

isUuidWire :: WireIR -> Bool
isUuidWire = \case
    WireUuidIR -> True
    WireOptionalIR inner -> isUuidWire inner
    WireNullableIR inner -> isUuidWire inner
    WireListIR inner -> isUuidWire inner
    _ -> False

renderFrontendSurfaceDomTokenConstants :: SurfaceIR -> [Text]
renderFrontendSurfaceDomTokenConstants surface =
    [ "export const " <> constName token <> "DomToken = " <> quote token <> " as const;"
    | token <- surface.surfaceBrowserDomTokens
    ] <> ["" | not (null surface.surfaceBrowserDomTokens)]

renderFrontendSurfaceRegistries :: [SurfaceIR] -> [Text]
renderFrontendSurfaceRegistries surfaces =
    [ "export type FrontendSurfaceName = " <> renderStringUnion (fmap (.surfaceName) surfaces) <> ";"
    , "export const FrontendSurfaceFragmentRegistry = " <> objectLiteral fragmentEntries <> " as const;"
    , "export function isFrontendSurfaceName(value: unknown): value is FrontendSurfaceName {"
    , "    return typeof value === \"string\" && Object.prototype.hasOwnProperty.call(FrontendSurfaceFragmentRegistry, value);"
    , "}"
    , "export function isFrontendSurfaceLiveFragmentName(surface: FrontendSurfaceName, value: unknown): value is string {"
    , "    return typeof value === \"string\" && (FrontendSurfaceFragmentRegistry[surface] as readonly string[]).includes(value);"
    , "}"
    , "export const FrontendSurfaceInteractionRegistry = " <> objectLiteral interactionEntries <> " as const;"
    , ""
    ]
  where
    fragmentEntries =
        [ (surface.surfaceName, arrayLiteral (fmap quote (surfaceLiveFragmentNames surface)))
        | surface <- surfaces
        ]
    interactionEntries =
        [ (surface.surfaceName, renderFrontendSurfaceInteractionDefinition surface)
        | surface <- surfaces
        , surface.surfaceName /= "surface-lab"
        , surfaceHasBrowserInteraction surface
        ]

surfaceHasBrowserInteraction :: SurfaceIR -> Bool
surfaceHasBrowserInteraction surface =
    not (null surface.surfaceSourceRefs)
        || not (null surface.surfaceDropzoneRefs)
        || not (null surface.surfaceActivationRefs)
        || not (null surface.surfaceSessions)

renderFrontendSurfaceInteractionDefinition :: SurfaceIR -> Text
renderFrontendSurfaceInteractionDefinition surface = objectLiteral
    [ ("sourceRefs", arrayLiteral (fmap renderSourceRef surface.surfaceSourceRefs))
    , ("dropzoneRefs", arrayLiteral (fmap renderDropzoneRef surface.surfaceDropzoneRefs))
    , ("activationRefs", arrayLiteral (fmap renderActivationRef surface.surfaceActivationRefs))
    , ("sessionKinds", arrayLiteral [renderBrowserSessionKind surface session | session <- surface.surfaceSessions])
    ]

renderSourceRef :: InteractionSourceRefIR -> Text
renderSourceRef ref = objectLiteral
    [ ("ref", quote ref.sourceRefName)
    , ("session", quote ref.sourceRefSession)
    , ("intent", quote ref.sourceRefIntent)
    , ("sourceField", quote ref.sourceRefSourceField)
    , ("compatibleDropzones", arrayLiteral (fmap quote ref.sourceRefCompatibleDropzones))
    , ("modifierVariants", arrayLiteral (fmap renderModifierVariant ref.sourceRefVariants))
    ]

renderModifierVariant :: InteractionModifierVariantIR -> Text
renderModifierVariant variant = objectLiteral
    [ ("semantic", quote variant.modifierVariantSemantic)
    , ("intent", quote variant.modifierVariantIntent)
    , ("effects", renderSessionEffects variant.modifierVariantEffects)
    ]

renderDropzoneRef :: InteractionDropzoneRefIR -> Text
renderDropzoneRef ref = objectLiteral
    [ ("ref", quote ref.dropzoneRefName)
    , ("session", quote ref.dropzoneRefSession)
    , ("targetField", quote ref.dropzoneRefTargetField)
    ]

renderActivationRef :: InteractionActivationRefIR -> Text
renderActivationRef ref = objectLiteral
    [ ("ref", quote ref.activationRefName)
    , ("intent", quote ref.activationRefIntent)
    , ("valueField", maybe "null" quote ref.activationRefValueField)
    , ("trigger", quote ref.activationRefTrigger)
    ]

renderBrowserSessionKind :: SurfaceIR -> Text -> Text
renderBrowserSessionKind surface session = objectLiteral
    [ ("kind", quote session)
    , ("effects", renderSessionEffects surface.surfaceEffects)
    ]

renderSessionEffects :: [(Text, [OptionIR])] -> Text
renderSessionEffects effects = objectLiteral
    [ ("global", arrayLiteral (mapMaybe renderGlobalEffect effects))
    , ("contextual", arrayLiteral (mapMaybe renderContextualEffect effects))
    ]

renderGlobalEffect :: (Text, [OptionIR]) -> Maybe Text
renderGlobalEffect ("clone-shadow", options) = Just $ renderCloneShadowEffect "bepis-pointer-clone-shadow" (optionLayerNames options)
renderGlobalEffect ("clone-shadow-copy", options) = Just $ renderCloneShadowEffect "bepis-pointer-clone-shadow bepis-pointer-clone-shadow-copy" (optionLayerNames options)
renderGlobalEffect _ = Nothing

renderCloneShadowEffect :: Text -> [Text] -> Text
renderCloneShadowEffect className layers = objectLiteral
    [ ("className", quote className)
    , ("kind", quote "clone-shadow")
    , ("layer", quote (fromMaybe "drag-preview" (listToMaybe layers)))
    , ("preserveGrabOffset", "true")
    , ("source", quote "pointer-marker")
    ]

renderContextualEffect :: (Text, [OptionIR]) -> Maybe Text
renderContextualEffect ("dropzone-highlight", _) = Just $ objectLiteral
    [ ("className", quote "bepis-dropzone-highlight")
    , ("kind", quote "dropzone-highlight")
    ]
renderContextualEffect _ = Nothing

optionLayerNames :: [OptionIR] -> [Text]
optionLayerNames = concatMap \case
    LayerOption name -> [name]
    LazyOption options -> optionLayerNames options
    EffectOption _ options -> optionLayerNames options
    ModifierVariantOption variant -> concatMap (optionLayerNames . snd) variant.modifierVariantEffects
    _ -> []

surfaceLiveFragmentNames :: SurfaceIR -> [Text]
surfaceLiveFragmentNames surface =
    [ fragment.fragmentName
    | fragment <- surface.surfaceFragments
    , optionsContainLive fragment.fragmentOptions
    ]

optionsContainLive :: [OptionIR] -> Bool
optionsContainLive = any \case
    LiveOption -> True
    LazyOption options -> optionsContainLive options
    EffectOption _ options -> optionsContainLive options
    ModifierVariantOption variant -> any (optionsContainLive . snd) variant.modifierVariantEffects
    _ -> False

objectLiteral :: [(Text, Text)] -> Text
objectLiteral fields = "{" <> Text.intercalate "," [quote key <> ":" <> value | (key, value) <- fields] <> "}"

arrayLiteral :: [Text] -> Text
arrayLiteral values = "[" <> Text.intercalate "," values <> "]"

renderFrontendSurfaceSupportSchemas :: [Text]
renderFrontendSurfaceSupportSchemas =
    renderSchemaFor BrowserGuardIR $
        TaggedUnionIR "FrontendSurfaceFragmentProtection" "FrontendSurfaceFragmentProtection" "kind"
            [ UnionCaseIR "Replace" "replace" []
            , UnionCaseIR "FocusedField" "focused-field"
                [ required "ActiveSelector" "activeSelector" WireTextIR
                , required "FieldKeyAttr" "fieldKeyAttr" WireTextIR
                , required "FieldNameFallback" "fieldNameFallback" WireBoolIR
                , nullable "ContainerSelector" "containerSelector" WireTextIR
                ]
            ]
  where
    required marker name wire = FieldIR marker name wire RequiredField
    nullable marker name wire = FieldIR marker name wire NullableFieldPresence

renderFrontendSurfaceMountConfigTypes :: [SurfaceIR] -> [Text]
renderFrontendSurfaceMountConfigTypes surfaces =
    renderFrontendSurfaceSupportSchemas
        <> [ "// FrontendSurface mount metadata is an exact surface-discriminated local envelope."
           , "// Executable URL/target/protection values exist only on these local fragment descriptors."
           ]
        <> concatMap renderFrontendSurfaceMountedFragmentConfig surfaces
        <> concatMap renderFrontendSurfaceMountConfig surfaces
        <> [ "export type FrontendSurfaceMountedFragmentConfig =" ]
        <> renderNamedUnion (fmap frontendSurfaceMountedFragmentConfigName surfaces)
        <> [ "export type FrontendSurfaceMountConfig =" ]
        <> renderNamedUnion (fmap frontendSurfaceMountConfigName surfaces)
        <> renderInboundCodec "FrontendSurfaceMountConfig" (orExpression ["is" <> frontendSurfaceMountConfigName surface <> "(value)" | surface <- surfaces])

renderFrontendSurfaceMountedFragmentConfig :: SurfaceIR -> [Text]
renderFrontendSurfaceMountedFragmentConfig surface =
    [ "export type "
        <> name
        <> " = { fragmentKey: ({ surface: "
        <> quote surface.surfaceName
        <> " } & "
        <> surfaceFragmentKeyUnionName surface
        <> "); targetId: string; url: string; protection: FrontendSurfaceFragmentProtection };"
    ]
        <> renderGuard name guardExpression
    where
        name = frontendSurfaceMountedFragmentConfigName surface
        guardExpression =
            "isRecord(value)"
                <> " && hasExactKeys(value, [\"fragmentKey\", \"targetId\", \"url\", \"protection\"])"
                <> " && isSurfaceFragmentKey(value[\"fragmentKey\"])"
                <> " && value[\"fragmentKey\"].surface === "
                <> quote surface.surfaceName
                <> " && typeof value[\"targetId\"] === \"string\" && value[\"targetId\"].length > 0"
                <> " && typeof value[\"url\"] === \"string\" && value[\"url\"].length > 0"
                <> " && isFrontendSurfaceFragmentProtection(value[\"protection\"])"

renderFrontendSurfaceMountConfig :: SurfaceIR -> [Text]
renderFrontendSurfaceMountConfig surface =
    [ "export type "
        <> name
        <> " = { surface: "
        <> quote surface.surfaceName
        <> "; scopeKey: string; mountKey: string; fragments: ReadonlyArray<"
        <> frontendSurfaceMountedFragmentConfigName surface
        <> ">; subscription: "
        <> subscriptionType
        <> " };"
    ]
        <> renderGuard name guardExpression
    where
        name = frontendSurfaceMountConfigName surface
        liveFragmentNames = surfaceLiveFragmentNames surface
        subscriptionType
            | null liveFragmentNames = "null"
            | otherwise = "{ scope: Extract<SurfaceScope, { surface: " <> quote surface.surfaceName <> " }> } | null"
        liveFragmentTest =
            "value[\"fragments\"].some((fragment) => isFrontendSurfaceLiveFragmentName("
                <> quote surface.surfaceName
                <> ", fragment.fragmentKey.kind))"
        validSubscription =
            "isRecord(value[\"subscription\"])"
                <> " && hasExactKeys(value[\"subscription\"], [\"scope\"])"
                <> " && isSurfaceScope(value[\"subscription\"].scope)"
                <> " && value[\"subscription\"].scope.surface === "
                <> quote surface.surfaceName
        subscriptionGuard
            | null liveFragmentNames = "value[\"subscription\"] === null"
            | otherwise =
                "((value[\"subscription\"] === null && !("
                    <> liveFragmentTest
                    <> ")) || (("
                    <> validSubscription
                    <> ") && ("
                    <> liveFragmentTest
                    <> ")))"
        guardExpression =
            "isRecord(value)"
                <> " && hasExactKeys(value, [\"surface\", \"scopeKey\", \"mountKey\", \"fragments\", \"subscription\"])"
                <> " && value[\"surface\"] === "
                <> quote surface.surfaceName
                <> " && typeof value[\"scopeKey\"] === \"string\" && value[\"scopeKey\"].length > 0"
                <> " && typeof value[\"mountKey\"] === \"string\" && value[\"mountKey\"].length > 0"
                <> " && Array.isArray(value[\"fragments\"]) && value[\"fragments\"].every((fragment) => is"
                <> frontendSurfaceMountedFragmentConfigName surface
                <> "(fragment))"
                <> " && ("
                <> subscriptionGuard
                <> ")"

frontendSurfaceMountedFragmentConfigName :: SurfaceIR -> Text
frontendSurfaceMountedFragmentConfigName surface = surfaceTypePrefix surface <> "MountedFragmentConfig"

frontendSurfaceMountConfigName :: SurfaceIR -> Text
frontendSurfaceMountConfigName surface = surfaceTypePrefix surface <> "MountConfig"

renderScope :: SurfaceIR -> ScopeIR -> [Text]
renderScope surface scope =
    renderRecordGuarded (surfaceTypePrefix surface <> typeNameFromMarker scope.scopeMarker <> "Scope") scope.scopeFields

renderFragment :: SurfaceIR -> FragmentIR -> [Text]
renderFragment surface fragment =
    renderRecordGuarded (surfaceTypePrefix surface <> typeNameFromMarker fragment.fragmentMarker <> "FragmentParams") fragment.fragmentParams

renderSchemaFor :: BrowserReachabilityIR -> SchemaIR -> [Text]
renderSchemaFor reachability schema =
    schemaTypeDeclaration schema <> renderReachableCodec reachability (schemaName schema) (schemaGuardExpression schema)

schemaName :: SchemaIR -> Text
schemaName = \case
    RecordIR _ name _ -> name
    EnumIR _ name _ -> name
    LiteralEnumIR _ name _ -> name
    TaggedUnionIR _ name _ _ -> name

schemaTypeDeclaration :: SchemaIR -> [Text]
schemaTypeDeclaration = \case
    RecordIR _ name fields -> ["export type " <> name <> " = " <> recordType fields <> ";"]
    EnumIR _ name values ->
        ["export type " <> name <> " ="] <> renderUnionValues values
    LiteralEnumIR _ name values ->
        ["export type " <> name <> " ="] <> renderUnionValues (fmap snd values)
    TaggedUnionIR _ name discriminator cases ->
        ["export type " <> name <> " ="] <> renderUnionCases discriminator cases

schemaGuardExpression :: SchemaIR -> Text
schemaGuardExpression = \case
    RecordIR _ _ fields -> recordGuardExpression fields
    EnumIR _ _ values -> isEnumExpression values
    LiteralEnumIR _ _ values -> isEnumExpression (fmap snd values)
    TaggedUnionIR _ _ discriminator cases -> "(" <> Text.intercalate " || " (fmap (caseGuard discriminator) cases) <> ")"

renderEventDetail :: BrowserReachabilityIR -> Text -> [FieldIR] -> [Text]
renderEventDetail BrowserUnreachableIR _ _ = []
renderEventDetail BrowserTypeOnlyIR _ _ = []
renderEventDetail reachability name fields =
    ["export type " <> name <> " = " <> recordType fields <> ";"]
        <> renderReachableCodec reachability name (recordGuardExpression fields)

renderRecordGuarded :: Text -> [FieldIR] -> [Text]
renderRecordGuarded name fields =
    ["export type " <> name <> " = " <> recordType fields <> ";"]
        <> renderGuard name (recordGuardExpression fields)

renderReachableCodec :: BrowserReachabilityIR -> Text -> Text -> [Text]
renderReachableCodec reachability name guardExpression =
    case reachability of
        BrowserUnreachableIR -> []
        BrowserTypeOnlyIR -> []
        BrowserGuardIR -> renderGuard name guardExpression
        BrowserInboundIR -> renderInboundCodec name guardExpression
        BrowserOutboundIR -> renderEncoder name
        BrowserBidirectionalIR -> renderInboundCodec name guardExpression <> renderEncoder name

renderGuard :: Text -> Text -> [Text]
renderGuard name guardExpression =
    [ "export function is" <> name <> "(value: unknown): value is " <> name <> " {"
    , "    return " <> guardExpression <> ";"
    , "}"
    , ""
    ]

renderInboundCodec :: Text -> Text -> [Text]
renderInboundCodec name guardExpression =
    renderGuard name guardExpression
        <> [ "export function parse" <> name <> "(value: unknown): " <> name <> " {"
           , "    if (is" <> name <> "(value)) return value;"
           , "    throw new Error(\"Invalid " <> name <> "\");"
           , "}"
           , ""
           ]

renderEncoder :: Text -> [Text]
renderEncoder name =
    [ "export function encode" <> name <> "(value: " <> name <> "): " <> name <> " { return value; }"
    , ""
    ]

renderUnionValues :: [Text] -> [Text]
renderUnionValues values =
    case values of
        [] -> ["    never;", ""]
        _  -> zipWith render values [0 :: Int ..]
    where
        render value index = (if index == 0 then "    " else "  | ") <> quote value <> if index == length values - 1 then ";" else ""

renderUnionCases :: Text -> [UnionCaseIR] -> [Text]
renderUnionCases discriminator cases =
    case cases of
        [] -> ["    never;", ""]
        _  -> zipWith render cases [0 :: Int ..]
    where
        render caseIR index =
            (if index == 0 then "    " else "  | ") <> (recordType (FieldIR "Discriminator" discriminator (WireRefIR (quote caseIR.unionCaseTag)) RequiredField : caseIR.unionCaseFields)) <> if index == length cases - 1 then ";" else ""

recordType :: [FieldIR] -> Text
recordType fields = "{ " <> Text.intercalate "; " (fmap renderField fields) <> " }"

renderField :: FieldIR -> Text
renderField field =
    propertyName field.fieldName <> optionalMarker field.fieldPresence <> ": " <> wireType field.fieldWire <> nullableSuffix field.fieldPresence

wireType :: WireIR -> Text
wireType = \case
    WireTextIR -> "string"
    WireIntIR -> "number"
    WireBoolIR -> "boolean"
    WireUuidIR -> wirePrimitiveTypeName WireUuidIR
    WireDayIR -> wirePrimitiveTypeName WireDayIR
    WireUnknownIR -> "unknown"
    WireListIR inner -> "ReadonlyArray<" <> wireType inner <> ">"
    WireMapIR key value -> "Record<" <> wireType key <> ", " <> wireType value <> ">"
    WireOptionalIR inner -> wireType inner <> " | undefined"
    WireNullableIR inner -> wireType inner <> " | null"
    WireRefIR name | Text.isPrefixOf "\"" name -> name
    WireRefIR name -> name
    WireSurfaceScopeIR -> "SurfaceScope"
    WireSurfaceFragmentKeyIR -> "SurfaceFragmentKey"

optionalMarker :: FieldPresence -> Text
optionalMarker = \case
    OptionalFieldPresence -> "?"
    RequiredField -> ""
    NullableFieldPresence -> ""

nullableSuffix :: FieldPresence -> Text
nullableSuffix = \case
    NullableFieldPresence -> " | null"
    RequiredField -> ""
    OptionalFieldPresence -> ""

recordGuardExpression :: [FieldIR] -> Text
recordGuardExpression fields =
    "isRecord(value) && hasExactKeys(value, [" <> Text.intercalate ", " (fmap (quote . (.fieldName)) fields) <> "])" <> mconcat (fmap fieldGuard fields)
    where
        fieldGuard field =
            let access = "value[" <> quote field.fieldName <> "]"
             in case field.fieldPresence of
                    RequiredField -> " && (" <> valueGuard access field.fieldWire <> ")"
                    OptionalFieldPresence -> " && (!(" <> quote field.fieldName <> " in value) || (" <> valueGuard access field.fieldWire <> "))"
                    NullableFieldPresence -> " && (" <> access <> " === null || (" <> valueGuard access field.fieldWire <> "))"

valueGuard :: Text -> WireIR -> Text
valueGuard access = \case
    WireTextIR -> "typeof " <> access <> " === \"string\""
    WireIntIR -> "typeof " <> access <> " === \"number\" && Number.isInteger(" <> access <> ")"
    WireBoolIR -> "typeof " <> access <> " === \"boolean\""
    WireUuidIR -> primitiveValueGuard access WireUuidIR
    WireDayIR -> primitiveValueGuard access WireDayIR
    WireUnknownIR -> "true"
    WireListIR inner -> "Array.isArray(" <> access <> ") && " <> access <> ".every((item) => " <> valueGuard "item" inner <> ")"
    WireMapIR key value -> "isRecord(" <> access <> ") && Object.entries(" <> access <> ").every(([key, entry]) => " <> valueGuard "key" key <> " && " <> valueGuard "entry" value <> ")"
    WireOptionalIR inner -> access <> " === undefined || " <> valueGuard access inner
    WireNullableIR inner -> access <> " === null || " <> valueGuard access inner
    WireRefIR name | Text.isPrefixOf "\"" name -> access <> " === " <> name
    WireRefIR name -> "is" <> name <> "(" <> access <> ")"
    WireSurfaceScopeIR -> "isSurfaceScope(" <> access <> ")"
    WireSurfaceFragmentKeyIR -> "isSurfaceFragmentKey(" <> access <> ")"

primitiveValueGuard :: Text -> WireIR -> Text
primitiveValueGuard access wire = "typeof " <> access <> " === " <> quote (wirePrimitiveRuntimeType wire)

isEnumExpression :: [Text] -> Text
isEnumExpression values = "typeof value === \"string\" && [" <> Text.intercalate ", " (fmap quote values) <> "].includes(value)"

caseGuard :: Text -> UnionCaseIR -> Text
caseGuard discriminator caseIR =
    "("
        <> recordGuardExpression
            (FieldIR "Discriminator" discriminator (WireRefIR (quote caseIR.unionCaseTag)) RequiredField : caseIR.unionCaseFields)
        <> ")"

surfaceTypePrefix :: SurfaceIR -> Text
surfaceTypePrefix surface = typeNameFromMarker surface.surfaceMarker

protocolTypeName :: Text -> Text
protocolTypeName name =
    name
        |> Text.splitOn "-"
        |> filter (not . Text.null)
        |> fmap title
        |> mconcat
    where
        title text =
            case Text.uncons text of
                Nothing -> ""
                Just (firstChar, rest) -> Text.singleton (Char.toUpper firstChar) <> rest

typeNameFromMarker :: Text -> Text
typeNameFromMarker marker
    | "-" `Text.isInfixOf` marker =
        marker
            |> Text.splitOn "-"
            |> filter (not . Text.null)
            |> fmap title
            |> mconcat
    | otherwise = Text.filter (/= '-') marker
    where
        title text =
            case Text.uncons text of
                Nothing -> ""
                Just (firstChar, rest) -> Text.singleton (Char.toUpper firstChar) <> rest

constName :: Text -> Text
constName marker =
    case Text.uncons (typeNameFromMarker marker) of
        Nothing -> "contract"
        Just (firstChar, rest) -> Text.singleton (Char.toLower firstChar) <> rest

propertyName :: Text -> Text
propertyName name
    | Text.all isIdentifierChar name && maybe False isIdentifierStart (fst <$> Text.uncons name) = name
    | otherwise = quote name
    where
        isIdentifierStart char = Char.isAlpha char || char == '_'
        isIdentifierChar char = Char.isAlphaNum char || char == '_'

quote :: Text -> Text
quote value = "\"" <> Text.replace "\\" "\\\\" (Text.replace "\"" "\\\"" value) <> "\""
