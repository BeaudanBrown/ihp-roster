tests :: Spec
tests = describe "Frontend contract generator foundation" do
    it "keeps the public generated file entrypoint FrontendContract-owned" do
        frontendContractsTypeScript `shouldSatisfy` Text.isPrefixOf "// @generated by Application.Helper.FrontendContract.Contracts"
        frontendContractsTypeScript `shouldSatisfy` Text.isInfixOf "export type OverlayLane"
        frontendContractsTypeScript `shouldSatisfy` Text.isInfixOf "export type SurfaceScope"
        frontendContractsTypeScript `shouldSatisfy` Text.isInfixOf "export type LiveUpdateCommand"
        frontendContractsTypeScript `shouldSatisfy` Text.isInfixOf "export type UiRegionTransitionProfile"
        frontendContractsTypeScript `shouldSatisfy` Text.isInfixOf "export type InteractionSessionEffect"

    it "registers one generated FrontendContract declaration block" do
        [(declaration.name, declaration.origin) | declaration <- frontendContractDeclarations]
            `shouldBe` [("FrontendContractGlobals", HaskellSchemaGenerated)]

    it "keeps the composition root free of handwritten protocol blocks" do
        source <- Text.readFile "Application/Helper/FrontendContract/Contracts.hs"
        source `shouldNotSatisfy` Text.isInfixOf "export type SurfaceScope"
        source `shouldNotSatisfy` Text.isInfixOf "export const InteractionDom"
        source `shouldNotSatisfy` Text.isInfixOf "export type UiRegionTransitionProfile"

    it "validates records, refs, arrays, nullable fields, and tagged unions through the IR JSON interpreter" do
        let scope = Live.SurfaceScope "timesheets" (Aeson.object ["venueId" Aeson..= ("11111111-1111-1111-1111-111111111111" :: Text), "weekOffset" Aeson..= (4 :: Int)])
        let fragment = Live.SurfaceWireFragment
                (Live.SurfaceFragmentKey "timesheets" "timesheet-day-section" (Aeson.object ["dayOffset" Aeson..= (2 :: Int)]))
                "timesheet-day-2"
                "/TimesheetDay?offset=2"
                True
                (Live.FocusedFieldProtection ".timesheet-input:focus" "data-field-key" True (Just ".timesheet-row"))
        let subscription = Live.SurfaceSubscription scope "timesheets:11111111-1111-1111-1111-111111111111:4" [fragment]
        let command = Live.Subscribe subscription "client-1" (Just 9)
        let message = Live.Invalidate scope "timesheets:11111111-1111-1111-1111-111111111111:4" 10 [fragment] (Just "client-2")

        AesonTypes.parseEither (validateContractValue "SurfaceSubscription") (Aeson.toJSON subscription) `shouldSatisfy` isRight
        AesonTypes.parseEither (validateContractValue "LiveUpdateCommand") (Aeson.toJSON command) `shouldSatisfy` isRight
        AesonTypes.parseEither (validateContractValue "LiveUpdateMessage") (Aeson.toJSON message) `shouldSatisfy` isRight
        Aeson.eitherDecode (Aeson.encode command) `shouldBe` Right command
        Aeson.eitherDecode (Aeson.encode message) `shouldBe` Right message

    it "rejects invalid surface scopes, fragments, enum values, and union discriminators through the IR JSON interpreter" do
        let badScope = Aeson.object ["surface" Aeson..= ("missing" :: Text), "scope" Aeson..= Aeson.object []]
        let badFragment = Aeson.object ["surface" Aeson..= ("timesheets" :: Text), "kind" Aeson..= ("missing" :: Text), "params" Aeson..= Aeson.object []]
        let badProtection = Aeson.object ["kind" Aeson..= ("missing" :: Text)]
        let badCommand = Aeson.object ["type" Aeson..= ("missing" :: Text)]

        AesonTypes.parseEither validateSurfaceScopeValue badScope `shouldSatisfy` isLeft
        AesonTypes.parseEither validateSurfaceFragmentKeyValue badFragment `shouldSatisfy` isLeft
        AesonTypes.parseEither (validateContractValue "SurfaceFragmentProtection") badProtection `shouldSatisfy` isLeft
        AesonTypes.parseEither (validateContractValue "LiveUpdateCommand") badCommand `shouldSatisfy` isLeft

    it "keeps generated contract validators, parsers, and encoders out of handwritten TypeScript" do
        offenders <- frontendGeneratedHelperOffenders (generatedContractTypeNames frontendContractsTypeScript)
        offenders `shouldBe` []

    it "keeps canonical generated strings out of handwritten frontend runtime" do
        offenders <- canonicalStringOffendersWithAllowedPrefixes
            ["frontend/ts"]
            [ "frontend/ts/generated/contracts.ts"
            , "frontend/ts/app-live-updates.ts"
            , "frontend/ts/live-updates/frontend-surface.ts"
            ]
            ["frontend/ts/tests/"]
            [".ts"]
            frontendRuntimeGeneratedOnlyStrings
        offenders `shouldBe` []

    it "has no legacy Frontend helper contract authorities" do
        frontendExists <- doesDirectoryExist "Application/Helper/Frontend"
        files <- if frontendExists then collectSourceFiles "Application/Helper/Frontend" else pure []
        files `shouldBe` []

    it "locks down raw TypeScript emitters to FrontendContract renderer internals only" do
        files <- collectSourceFiles "Application/Helper/FrontendContract"
        offenders <- fmap concat $ forM files \path -> do
            source <- Text.readFile path
            pure
                [ (path, pattern)
                | path /= "Application/Helper/FrontendContract/TypeScript.hs"
                , path /= "Application/Helper/FrontendContract/Contracts.hs"
                , pattern <- rawEmitterPatterns
                , pattern `Text.isInfixOf` source
                ]
        offenders `shouldBe` []

generatedContractTypeNames :: Text -> [Text]
generatedContractTypeNames source =
    [ Text.takeWhile (/= ' ') rest
    | line <- Text.lines source
    , Just rest <- [Text.stripPrefix "export type " line]
    ]

frontendGeneratedHelperOffenders :: [Text] -> IO [(FilePath, Text)]
frontendGeneratedHelperOffenders typeNames = do
    files <- collectSourceFiles "frontend/ts"
    fmap concat $ forM files \path -> do
        if path `elem` ["frontend/ts/generated/contracts.ts", "frontend/ts/live-updates/frontend-surface.ts"]
            then pure []
            else do
                source <- Text.readFile path
                pure
                    [ (path, helper)
                    | typeName <- typeNames
                    , prefix <- ["is", "parse", "encode"]
                    , let helper = prefix <> typeName
                    , any (`Text.isInfixOf` source)
                        [ "function " <> helper
                        , "const " <> helper
                        , "let " <> helper
                        , "var " <> helper
                        ]
                    ]

frontendRuntimeGeneratedOnlyStrings :: [Text]
frontendRuntimeGeneratedOnlyStrings =
    [ "data-bepis-"
    , "bepis:page-ready"
    , "bepis:live-fragments-refresh"
    , "bepis:interaction-intent"
    , "bepis:intent-submit"
    , "bepis:interaction-session-start"
    , "bepis:interaction-session-end"
    , "bepis:interaction-session-cancel-request"
    ]

canonicalStringOffendersWithAllowedPrefixes :: [FilePath] -> [FilePath] -> [FilePath] -> [FilePath] -> [Text] -> IO [(FilePath, Text)]
canonicalStringOffendersWithAllowedPrefixes roots allowedFiles allowedPrefixes extensions needles = do
    files <- fmap List.sort (concat <$> mapM collectSourceFiles roots)
    fmap concat $ forM files \path -> do
        if path `elem` allowedFiles || any (`List.isPrefixOf` path) allowedPrefixes || takeExtension path `notElem` extensions
            then pure []
            else do
                source <- Text.readFile path
                pure [(path, needle) | needle <- needles, needle `Text.isInfixOf` source]

rawEmitterPatterns :: [Text]
rawEmitterPatterns =
    [ "TSRawDeclaration"
    , "\"export type"
    , "\"export interface"
    , "\"export const"
    , "\"export function"
    , "stringUnionDeclaration"
    ]

collectSourceFiles :: FilePath -> IO [FilePath]
collectSourceFiles root = do
    exists <- doesDirectoryExist root
    if not exists
        then pure []
        else go root
    where
        go path = do
            entries <- listDirectory path
            fmap concat $ forM entries \entry -> do
                let child = path </> entry
                isDirectory <- doesDirectoryExist child
                if isDirectory
                    then go child
                    else pure [child | takeExtension child `elem` [".hs", ".ts"]]
