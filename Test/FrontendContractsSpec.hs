renderShouldSucceed :: HasCallStack => [SomeFrontendCodec] -> IO Text
renderShouldSucceed codecs =
    case renderFrontendContracts codecs of
        Left message -> expectationFailure (cs message) >> pure ""
        Right source -> pure source

