import { expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { surfaceConfigDomAttr, surfaceDomAttr } from '../frontend/ts/generated/contracts';
import { daysheetTest as test, openDaysheet, openDaysheetDate, saveDaysheetText, saveDaysheetChange } from './support/daysheet';
import { expectNoHorizontalViewportOverflow } from './support/responsive';

test('previews selected saved reports, refreshes across tabs and distinguishes Draft from Live', async ({ page, daysheet, browser }) => {
    await openDaysheet(page, daysheet);
    const originalUrl = page.url();
    await page.getByRole('button', { name: 'Configure Daysheets', exact: true }).click();
    await page.getByRole('link', { name: 'Add report', exact: true }).click();
    await page.getByLabel('Report name', { exact: true }).fill('Manager preview');
    await page.getByLabel('Report targets', { exact: true }).selectOption('formatted-and-excel');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    const report = page.getByRole('region', { name: 'Report: Manager preview', exact: true });
    await report.getByRole('link', { name: 'Add report section', exact: true }).click();
    await page.getByLabel('Section name', { exact: true }).fill('Selected summary');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    const section = report.getByRole('region', { name: 'Section: Selected summary', exact: true });
    for (const label of ['Comments', 'Count', 'Receipt total']) {
        await section.getByText('Add content to Selected summary', { exact: true }).click();
        await section.getByRole('link', { name: 'Add field or summary', exact: true }).click();
        await page.getByLabel('Field or summary', { exact: true }).selectOption({ label });
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    }
    await section.getByText('Add content to Selected summary', { exact: true }).click();
    await section.getByRole('link', { name: 'Add table: Receipts', exact: true }).click();
    await page.getByLabel('Columns', { exact: true }).selectOption([{ label: 'Terminal' }, { label: 'Receipt' }]);
    await page.getByLabel('Group rows by', { exact: true }).selectOption({ label: 'Terminal' });
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await section.getByText('Add content to Selected summary', { exact: true }).click();
    await section.getByRole('link', { name: 'Add advisory check', exact: true }).click();
    await page.getByLabel('Boolean condition', { exact: true }).selectOption({ label: 'Checked' });
    await page.getByLabel('Pass message', { exact: true }).fill('Checks acknowledged');
    await page.getByLabel('Concern message', { exact: true }).fill('Review closing checks');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await page.getByRole('button', { name: 'Publish draft', exact: true }).click();
    await expect(page.getByText('No unpublished changes.', { exact: true })).toBeVisible();
    await page.goto(originalUrl);
    await expect(page.getByRole('button', { name: 'Preview: Manager preview', exact: true })).toHaveCount(0);
    await openDaysheetDate(page, '2026-10-02');
    const dailyUrl = page.url();
    const literal = '<script>unsafe()</script> =HYPERLINK(plain text)';
    await saveDaysheetText(page, page.getByLabel('Comments', { exact: true }), literal);
    await saveDaysheetText(page, page.getByLabel('Count', { exact: true }), '0');
    const draftDownloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download Excel: Manager preview', exact: true }).click();
    const draftDownload = await draftDownloadPromise;
    expect(draftDownload.suggestedFilename()).toBe('daysheet-manager-preview-2026-10-02-draft.xlsx');
    expect(await draftDownload.failure()).toBeNull();
    const draftBytes = await readFile((await draftDownload.path())!);
    expect(draftBytes.subarray(0, 2).toString()).toBe('PK');
    await page.getByRole('button', { name: 'Preview: Manager preview', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Manager preview', exact: true })).toBeVisible();
    await expect(page.getByText('Draft preview', { exact: true })).toBeVisible();
    await expect(page.getByText(literal, { exact: true })).toBeVisible();
    await expect(page.locator('script').filter({ hasText: 'unsafe()' })).toHaveCount(0);
    await expect(page.getByText('0', { exact: true })).toBeVisible();
    await expect(page.getByText('Receipt total', { exact: true }).locator('..')).toContainText('Unavailable: Enter Receipt.');
    await expect(page.getByText('Not evaluated: Required input has not been entered.', { exact: true })).toBeVisible();
    await expect(page.getByRole('region', { name: 'Receipts', exact: true }).getByRole('cell', { name: 'Terminal 1', exact: true })).toBeVisible();
    await expect(page.getByRole('columnheader')).toHaveText(['Terminal', 'Receipt']);
    await expect(page.getByText('Rate', { exact: true })).toHaveCount(0);
    const config = await page.locator(`[${surfaceDomAttr}="daysheet"]`).getAttribute(surfaceConfigDomAttr);
    expect(JSON.parse(config!).fragments).toHaveLength(1);
    await expectNoHorizontalViewportOverflow(page);
    const editor = await page.context().newPage();
    await editor.goto(dailyUrl);
    await expect(editor.getByRole('heading', { name: 'Daysheet — 2026-10-02', exact: true })).toBeVisible();
    const refetch = page.waitForResponse(response => response.url().includes('/ShowDaysheetReportBody') && response.status() === 200);
    await saveDaysheetText(editor, editor.getByLabel('Comments', { exact: true }), 'Saved correction');
    await refetch;
    await expect(page.getByText('Saved correction', { exact: true })).toBeVisible();
    await saveDaysheetText(editor, editor.getByRole('region', { name: 'Receipts', exact: true }).getByLabel('Receipt', { exact: true }).first(), '0');
    await expect(page.getByRole('cell', { name: '0 AUD', exact: true })).toBeVisible();
    const checked = editor.getByLabel('Checked', { exact: true });
    await saveDaysheetChange(editor, checked, () => checked.selectOption('false'));
    await expect(page.getByText('Concern: Review closing checks', { exact: true })).toBeVisible();
    await saveDaysheetChange(editor, checked, () => checked.selectOption('true'));
    await expect(page.getByText('Passed: Checks acknowledged', { exact: true })).toBeVisible();
    await editor.getByRole('button', { name: 'Submit saved Daysheet', exact: true }).click();
    await expect(page.getByText('Live preview', { exact: true })).toBeVisible();
    await expect(page.getByText('Draft preview', { exact: true })).toHaveCount(0);
    await saveDaysheetText(editor, editor.getByLabel('Comments', { exact: true }), 'After submission');
    await expect(page.getByText('After submission', { exact: true })).toBeVisible();
    await expectNoHorizontalViewportOverflow(page);
    // Send stays gated until this client's focused edit is saved and acknowledged.
    await saveDaysheetChange(editor, editor.getByLabel('Comments', { exact: true }), async () => {
        await editor.getByLabel('Comments', { exact: true }).fill('Frozen from settled entry');
        await expect(editor.getByRole('button', { name: 'Send: Manager preview', exact: true })).toBeDisabled();
    });
    await editor.getByRole('button', { name: 'Send: Manager preview', exact: true }).click();
    await expect(editor.getByRole('heading', { name: 'Send report: Manager preview', exact: true })).toBeVisible();
    await expect(editor.getByText('No recipients are configured. This captures a report but sends no email.', { exact: true })).toBeVisible();
    await editor.getByRole('button', { name: 'Capture and send report', exact: true }).click();
    await expect(editor.getByText('Frozen report', { exact: true })).toBeVisible();
    await expect(editor.getByText('Frozen from settled entry', { exact: true })).toBeVisible();
    await expectNoHorizontalViewportOverflow(editor);
    await page.goto(dailyUrl);
    const historyRefresh = editor.waitForResponse(response => response.url().includes('/ShowDaysheetHistoryBody') && response.status() === 200);
    await saveDaysheetText(page, page.getByLabel('Comments', { exact: true }), 'New live value after capture');
    await historyRefresh;
    await expect(editor.getByText('Frozen from settled entry', { exact: true })).toBeVisible();
    await expect(editor.getByText('New live value after capture', { exact: true })).toHaveCount(0);
    await editor.close();
    const native = await browser.newContext({ storageState: await page.context().storageState(), javaScriptEnabled: false, viewport: page.viewportSize() });
    const nativePage = await native.newPage();
    await nativePage.goto(dailyUrl);
    const liveDownloadPromise = nativePage.waitForEvent('download');
    await nativePage.getByRole('button', { name: 'Download Excel: Manager preview', exact: true }).click();
    const liveDownload = await liveDownloadPromise;
    expect(liveDownload.suggestedFilename()).toBe('daysheet-manager-preview-2026-10-02-live.xlsx');
    expect(await liveDownload.failure()).toBeNull();
    await nativePage.getByRole('button', { name: 'Preview: Manager preview', exact: true }).click();
    await expect(nativePage.getByRole('heading', { name: 'Manager preview', exact: true })).toBeVisible();
    await expect(nativePage.getByText('Live preview', { exact: true })).toBeVisible();
    await nativePage.getByRole('link', { name: 'Return to Daysheet', exact: true }).click();
    await nativePage.getByRole('button', { name: 'Send: Manager preview', exact: true }).click();
    await nativePage.getByRole('button', { name: 'Capture and send report', exact: true }).click();
    await expect(nativePage.getByText('Frozen report', { exact: true })).toBeVisible();
    await expect(nativePage.getByText('New live value after capture', { exact: true })).toBeVisible();
    await nativePage.getByRole('link', { name: 'Older report', exact: true }).click();
    await expect(nativePage.getByText('Frozen from settled entry', { exact: true })).toBeVisible();
    await expect(nativePage.getByText('New live value after capture', { exact: true })).toHaveCount(0);
    await native.close();
});
