import { expect } from '@playwright/test';
import { daysheetTest as test, openDaysheet } from './support/daysheet';
import { expectNoHorizontalViewportOverflow } from './support/responsive';

test.describe('Daysheet designer controls', () => {
    test('stages typed fields and lists, renames and explicitly publishes', async ({ page, daysheet }) => {
        await openDaysheet(page, daysheet);
        await page.getByRole('button', { name: 'Configure Daysheets', exact: true }).click();
        await expect(page.getByRole('heading', { name: 'Daysheet designer', exact: true })).toBeVisible();
        await page.getByRole('link', { name: 'Add root field', exact: true }).click();
        await page.getByLabel('Field name', { exact: true }).fill('Door receipts');
        await page.getByLabel('Field type', { exact: true }).selectOption('money');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(page.getByRole('link', { name: 'Door receipts', exact: true })).toBeVisible();
        await page.getByRole('link', { name: 'Door receipts', exact: true }).click();
        await expect(page.getByLabel('Field type', { exact: true })).toHaveValue('money');
        await page.getByLabel('Field name', { exact: true }).fill('Door takings');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(page.getByRole('link', { name: 'Door takings', exact: true })).toBeVisible();
        await page.getByRole('link', { name: 'Add list', exact: true }).click();
        await page.getByLabel('List name', { exact: true }).fill('Adjustments');
        await page.getByLabel('List mode', { exact: true }).selectOption('open-daily');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(page.getByRole('heading', { name: 'Adjustments', exact: true })).toBeVisible();
        await expectNoHorizontalViewportOverflow(page);
        await page.getByRole('button', { name: 'Publish draft', exact: true }).click();
        await expect(page.getByText('No unpublished changes.', { exact: true })).toBeVisible();
        await expect(page.getByRole('link', { name: 'Door takings', exact: true })).toBeVisible();
    });

    test('edits and retires staged references without changing an existing Daysheet', async ({ page, daysheet }) => {
        await openDaysheet(page, daysheet);
        const capturedUrl = page.url();
        await page.getByRole('button', { name: 'Configure Daysheets', exact: true }).click();
        await page.getByRole('heading', { name: 'Terminals', exact: true }).locator('..').getByRole('link', { name: 'Add field to list', exact: true }).click();
        await page.getByLabel('Field name', { exact: true }).fill('Float');
        await page.getByLabel('Field type', { exact: true }).selectOption('money');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        const records = page.getByRole('region', { name: 'Reference records: Terminals', exact: true });
        await records.getByRole('group', { name: 'Terminal 1', exact: true }).getByRole('link', { name: 'Label', exact: true }).click();
        await page.getByLabel('Label', { exact: true }).fill('Inside terminal');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(records.getByRole('group', { name: 'Inside terminal', exact: true })).toBeVisible();
        await records.getByRole('group', { name: 'Inside terminal', exact: true }).getByRole('link', { name: 'Float', exact: true }).click();
        await page.getByLabel('Float', { exact: true }).fill('12.345');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(page.getByText('Enter an AUD amount with whole-cent precision.', { exact: true })).toBeVisible();
        await expect(page.getByLabel('Float', { exact: true })).toHaveValue('12.345');
        await page.getByLabel('Float', { exact: true }).fill('12.34');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(records.getByRole('group', { name: 'Inside terminal', exact: true })).toContainText('12.34');
        await records.getByRole('group', { name: 'Terminal 2', exact: true }).getByRole('button', { name: 'Retire reference record', exact: true }).click();
        await expect(records.getByRole('group', { name: 'Terminal 2', exact: true })).toHaveCount(0);
        await records.getByRole('button', { name: 'Add reference record', exact: true }).click();
        const added = records.getByRole('group').filter({ has: page.getByRole('heading', { name: /^Record / }) });
        await added.getByRole('link', { name: 'Label', exact: true }).click();
        await page.getByLabel('Label', { exact: true }).fill('Spare terminal');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(records.getByRole('group', { name: 'Spare terminal', exact: true })).toBeVisible();
        await expectNoHorizontalViewportOverflow(page);
        await page.getByRole('button', { name: 'Publish draft', exact: true }).click();
        await expect(page.getByText('No unpublished changes.', { exact: true })).toBeVisible();
        await page.goto(capturedUrl);
        const receipts = page.getByRole('region', { name: 'Receipts', exact: true });
        await expect(receipts.getByText('Terminal 1', { exact: true })).toBeVisible();
        await expect(receipts.getByText('Terminal 2', { exact: true })).toBeVisible();
        await expect(receipts.getByText('Inside terminal', { exact: true })).toHaveCount(0);
        await expect(receipts.getByText('Spare terminal', { exact: true })).toHaveCount(0);
    });

    test('authors, renames and orders choice options without replacing their identities', async ({ page, daysheet }) => {
        await openDaysheet(page, daysheet);
        await page.getByRole('button', { name: 'Configure Daysheets', exact: true }).click();
        await page.getByRole('link', { name: 'Add root field', exact: true }).click();
        await page.getByLabel('Field name', { exact: true }).fill('Payment category');
        await page.getByLabel('Field type', { exact: true }).selectOption('choice');
        await page.getByLabel('First option (new choice fields only)', { exact: true }).fill('Sale');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        const options = page.getByRole('group', { name: 'Choice options: Payment category', exact: true });
        await options.getByText('Choice options', { exact: true }).click();
        await options.getByRole('link', { name: 'Add option', exact: true }).click();
        await page.getByLabel('Option name', { exact: true }).fill('Expense');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await options.getByText('Choice options', { exact: true }).click();
        const originalLink = await options.getByRole('link', { name: 'Expense', exact: true }).getAttribute('href');
        if (!originalLink) throw new Error('Expected an option edit URL.');
        await options.getByRole('link', { name: 'Expense', exact: true }).click();
        await page.getByLabel('Option name', { exact: true }).fill('Supplier payment');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await options.getByText('Choice options', { exact: true }).click();
        await expect(options.getByRole('link', { name: 'Supplier payment', exact: true })).toHaveAttribute('href', originalLink);
        await options.getByRole('link', { name: 'Supplier payment', exact: true }).locator('..').getByRole('button', { name: 'Move option earlier', exact: true }).click();
        await expect(options.getByRole('list', { includeHidden: true }).getByRole('link', { includeHidden: true })).toHaveText(['Supplier payment', 'Sale']);
        await options.getByText('Choice options', { exact: true }).click();
        await options.getByRole('link', { name: 'Sale', exact: true }).locator('..').getByRole('button', { name: 'Remove option', exact: true }).click();
        await expect(options.getByRole('link', { name: 'Sale', exact: true, includeHidden: true })).toHaveCount(0);
        await options.getByText('Choice options', { exact: true }).click();
        await expect(options.getByRole('button', { name: 'Remove option', exact: true })).toBeDisabled();
        await expectNoHorizontalViewportOverflow(page);
        await page.getByRole('button', { name: 'Publish draft', exact: true }).click();
        await expect(page.getByText('No unpublished changes.', { exact: true })).toBeVisible();
    });

    test('authors independent report and entry layouts with ordered tables and advisory checks', async ({ page, daysheet }) => {
        await openDaysheet(page, daysheet);
        const capturedUrl = page.url();
        await page.getByRole('button', { name: 'Configure Daysheets', exact: true }).click();
        await page.getByRole('link', { name: 'Add report', exact: true }).click();
        await page.getByLabel('Report name', { exact: true }).fill('Closing pack');
        await page.getByLabel('Report targets', { exact: true }).selectOption('formatted-and-excel');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        const report = page.getByRole('region', { name: 'Report: Closing pack', exact: true });
        await report.getByRole('link', { name: 'Add report section', exact: true }).click();
        await page.getByLabel('Section name', { exact: true }).fill('Reconciliation');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        const section = report.getByRole('region', { name: 'Section: Reconciliation', exact: true });
        await section.getByText('Add content to Reconciliation', { exact: true }).click();
        await section.getByRole('link', { name: 'Add table: Receipts', exact: true }).click();
        await page.getByLabel('Columns', { exact: true }).selectOption([{ label: 'Terminal' }, { label: 'Receipt' }]);
        await page.getByLabel('Group rows by', { exact: true }).selectOption({ label: 'Terminal' });
        await page.getByLabel('Sort rows by', { exact: true }).selectOption([{ label: 'Receipt' }]);
        await page.getByLabel('Descending sort fields', { exact: true }).selectOption([{ label: 'Receipt' }]);
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        const table = section.getByRole('link', { name: 'Table: Receipts', exact: true }).locator('..');
        await table.getByText('Column and sort order', { exact: true }).click();
        await table.getByRole('button', { name: 'Move column later', exact: true }).first().click();
        await section.getByRole('link', { name: 'Table: Receipts', exact: true }).click();
        await expect(page.getByLabel('Columns', { exact: true }).locator('option:checked')).toHaveText(['Receipt', 'Terminal']);
        await expect(page.getByLabel('Sort rows by', { exact: true }).locator('option:checked')).toHaveText(['Receipt']);
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await section.getByText('Add content to Reconciliation', { exact: true }).click();
        await section.getByRole('link', { name: 'Add advisory check', exact: true }).click();
        const conditions = page.getByLabel('Boolean condition', { exact: true });
        await expect(conditions.locator('option')).not.toContainText(['Comments']);
        await conditions.selectOption({ label: 'Checked' });
        await page.getByLabel('Pass message', { exact: true }).fill('Checks acknowledged');
        await page.getByLabel('Concern message', { exact: true }).fill('Review closing checks');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(section.getByRole('link', { name: 'Check: Checks acknowledged', exact: true })).toBeVisible();
        await section.getByRole('link', { name: 'Reconciliation', exact: true }).click();
        await page.getByLabel('Section name', { exact: true }).fill('Close totals');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(report.getByRole('region', { name: 'Section: Close totals', exact: true }).getByRole('link', { name: 'Table: Receipts', exact: true })).toBeVisible();
        await page.getByRole('link', { name: 'Add entry section', exact: true }).click();
        await page.getByLabel('Section name', { exact: true }).fill('Extra notes');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        const entry = page.getByRole('region', { name: 'Entry layout', exact: true }).getByRole('region', { name: 'Section: Extra notes', exact: true });
        await entry.getByText('Add content to Extra notes', { exact: true }).click();
        await entry.getByRole('link', { name: 'Add instructions', exact: true }).click();
        await page.getByLabel('Plain-text instructions', { exact: true }).fill('Daily notes stay together.');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(entry.getByRole('link', { name: 'Instructions: Daily notes stay together.', exact: true })).toBeVisible();
        await expect(report.getByText('Daily notes stay together.', { exact: false })).toHaveCount(0);
        await expectNoHorizontalViewportOverflow(page);
        await page.getByRole('button', { name: 'Publish draft', exact: true }).click();
        await expect(page.getByText('No unpublished changes.', { exact: true })).toBeVisible();
        await page.goto(capturedUrl);
        await expect(page.getByRole('heading', { name: 'Extra notes', exact: true })).toHaveCount(0);
    });

    test('retains a dirty editor across another tab saving and supports explicit discard', async ({ page, context, daysheet }) => {
        await openDaysheet(page, daysheet);
        await page.getByRole('button', { name: 'Configure Daysheets', exact: true }).click();
        await expect(page.getByRole('heading', { name: 'Daysheet designer', exact: true })).toBeVisible();
        const observer = await context.newPage();
        await observer.goto(page.url());
        await expect(observer.getByRole('link', { name: 'Comments', exact: true })).toBeVisible();
        await page.getByRole('link', { name: 'Comments', exact: true }).click();
        await page.getByLabel('Field name', { exact: true }).fill('Unsaved local comments');
        const other = await context.newPage();
        await other.goto(page.url());
        await other.getByLabel('Field name', { exact: true }).fill('Saved closing comments');
        await other.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(other.getByRole('link', { name: 'Saved closing comments', exact: true })).toBeVisible();
        await expect(observer.getByRole('link', { name: 'Saved closing comments', exact: true })).toBeVisible();
        await expect(page.getByLabel('Field name', { exact: true })).toHaveValue('Unsaved local comments');
        await page.getByRole('button', { name: 'Save draft', exact: true }).click();
        await expect(page.getByText('This configuration changed. Reload and review your changes before saving.', { exact: true })).toBeVisible();
        await expect(page.getByLabel('Field name', { exact: true })).toHaveValue('Unsaved local comments');
        await page.getByRole('link', { name: 'Discard edit and return', exact: true }).click();
        await expect(page.getByRole('link', { name: 'Saved closing comments', exact: true })).toBeVisible();
        await expect(page.getByRole('link', { name: 'Unsaved local comments', exact: true })).toHaveCount(0);
        await other.close();
        await observer.close();
    });
});
